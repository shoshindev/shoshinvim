"""Write THIRD_PARTY_NOTICES.md: the material ShoshinVim adapts and the license of every
Go module compiled into the release executables (all five targets).

  python3 scripts/third-party-notices.py          # rewrite the file
  python3 scripts/third-party-notices.py --check  # fail if it is out of date
"""
import os, pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'THIRD_PARTY_NOTICES.md'
TARGETS = [('darwin', 'arm64'), ('darwin', 'amd64'), ('linux', 'arm64'), ('linux', 'amd64'), ('windows', 'amd64')]
LICENSE_FILE = re.compile(r'^(LICEN[CS]E|COPYING|NOTICE)([.-].*)?$', re.I)

