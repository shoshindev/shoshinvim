// LuaString uses decimal byte escapes, avoiding JSON's unsupported Lua unicode escapes.
func LuaString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, c := range []byte(s) {
		switch {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c < 32 || c >= 127:
			fmt.Fprintf(&b, "\\%03d", c)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}
func Lua(v any) string {
	switch x := v.(type) {
	case string:
		return LuaString(x)
	case bool:
		if x {
			return "true"
		}
		return "false"
	case float64:
		return strconv.FormatFloat(x, 'f', -1, 64)
	case int:
		return strconv.Itoa(x)
	}
	panic("unsupported validated Lua value")
}
func sorted[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func Generate(s State) (map[string]string, error) {
	if err := LoadCatalog().Validate(s); err != nil {
		return nil, err
	}
	s = withLegacyWorkspace(s)
	files := map[string]string{}
	modules := []string{}
	add := func(name, body string) {
		if body != "" {
			files["lua/user_config/"+name+".lua"] = "-- Generated by ShoshinVim. Put manual changes in user.lua.\n" + body
			modules = append(modules, name)
		}
	}
	var opts strings.Builder
	for _, id := range sorted(s.Values) {
		if strings.HasPrefix(id, "options.") {
			// Setting these options can open output files even in an otherwise clean process.
			sideEffect := id == "options.verbosefile" || id == "options.shadafile"
			if sideEffect {
				opts.WriteString("if not vim.g.shoshinvim_probe then\n")
			}
			fmt.Fprintf(&opts, "vim.opt[%s] = %s\n", LuaString(strings.TrimPrefix(id, "options.")), Lua(s.Values[id]))
			if sideEffect {
				opts.WriteString("end\n")
			}
		}
	}
	add("options", opts.String())
	var autocmds strings.Builder
	for _, ft := range sorted(s.Filetypes) {
		fmt.Fprintf(&autocmds, "vim.api.nvim_create_autocmd('FileType', { group = vim.api.nvim_create_augroup(%s, { clear = true }), pattern = %s, callback = function()\n", LuaString("Shoshin_"+ft), LuaString(ft))
		for _, name := range sorted(s.Filetypes[ft]) {
			fmt.Fprintf(&autocmds, "  vim.opt_local[%s] = %s\n", LuaString(name), Lua(s.Filetypes[ft][name]))
		}
		autocmds.WriteString("end })\n")
	}
	autocmds.WriteString(editorAutocmds(s))
	add("autocmds", autocmds.String())
	add("plugins", pluginLua(s))
	add("syntax", syntaxLua(s))
	add("appearance", appearanceLua(s))
	add("navigation", navigationLua(s))
	add("git", gitLua(s))
	if _, ok := s.Values["diagnostics.virtual_text"]; ok {
		add("diagnostics", "vim.diagnostic.config({ virtual_text = "+Lua(s.Values["diagnostics.virtual_text"])+", severity_sort = true })\n")
	}
	add("lsp", completionCapabilities(s)+lspLua(s))
	if engine := completionEngineLua(s); engine != "" {
		add("completion", engine)
	} else if Enabled(s, "completion.native") {
		add("completion", `vim.api.nvim_create_autocmd('LspAttach', {
  group = vim.api.nvim_create_augroup('ShoshinCompletion', { clear = true }),
  callback = function(event)
    local client = vim.lsp.get_client_by_id(event.data.client_id)
    if client and client:supports_method('textDocument/completion') then
      vim.lsp.completion.enable(true, client.id, event.buf, { autotrigger = true })
    end
  end,
})
`)
	}
	if Value(s, "formatting.provider", "native") == "conform" {
		add("formatting", `local ok, conform = false, nil
if not vim.g.shoshinvim_probe then ok, conform = pcall(require, 'conform') end
if ok then
  conform.setup({ formatters = {
`+formatterCommands(s)+`  }, formatters_by_ft = {
    lua = { 'stylua' }, javascript = { 'prettier' }, typescript = { 'prettier' },
    javascriptreact = { 'prettier' }, typescriptreact = { 'prettier' },
    html = { 'prettier' }, css = { 'prettier' }, json = { 'prettier' },
  }`+func() string {
			if Enabled(s, "formatting.on_save") {
				return ", format_on_save = { timeout_ms = 2000, lsp_format = 'fallback' }"
			}
			return ""
		}()+` })
  vim.api.nvim_create_user_command('ShoshinFormat', function() conform.format({ async = true, lsp_format = 'fallback' }) end, {})
else
  vim.api.nvim_create_user_command('ShoshinFormat', function() vim.lsp.buf.format({ async = true }) end, {})
end
`)
	} else {
		body := "vim.api.nvim_create_user_command('ShoshinFormat', function() vim.lsp.buf.format({ async = true }) end, {})\n"
		if Enabled(s, "formatting.on_save") {
			body += `vim.api.nvim_create_autocmd('BufWritePre', { group = vim.api.nvim_create_augroup('ShoshinFormat', { clear = true }), callback = function(event)
  local clients = vim.lsp.get_clients({ bufnr = event.buf, method = 'textDocument/formatting' })
  if #clients == 1 then vim.lsp.buf.format({ bufnr = event.buf, id = clients[1].id, timeout_ms = 2000 }) end
end })
`
		}
		add("formatting", body)
	}
	add("lint", lintLua(s))
	add("debug", debugLua(s))
	add("interface", interfaceLua(s))
	add("keymaps", keymapsLua(s))
	var init strings.Builder
	init.WriteString("-- Generated by ShoshinVim. This configuration has no ShoshinVim runtime dependency.\n")
	init.WriteString("local config_root = vim.fn.fnamemodify(debug.getinfo(1, 'S').source:sub(2), ':p:h')\nvim.opt.rtp:prepend(config_root)\nvim.g.shoshinvim_config_root = config_root\n")
	if _, chosen := s.Values["keymaps.leader"]; chosen || Value(s, "keymaps.style", "none") != "none" {
		// The leader must be set before plugins and shortcuts are loaded.
		local := leaderKey(s)
		if Value(s, "keymaps.style", "none") == "lazyvim" {
			local = "\\" // LazyVim keeps Neovim's default local leader.
		}
		fmt.Fprintf(&init, "vim.g.mapleader = %s\nvim.g.maplocalleader = %s\n", LuaString(leaderKey(s)), LuaString(local))
	}
	// Each module loads on its own so one failure (a broken plugin, an unwritable cache)
	// cannot disable the modules after it. Validation probes stay strict.
	init.WriteString(`local function load(name)
  if vim.g.shoshinvim_probe then return require('user_config.' .. name) end
  local ok, err = pcall(require, 'user_config.' .. name)
  if not ok then
    vim.schedule(function() vim.notify('ShoshinVim: ' .. name .. ' did not load: ' .. tostring(err), vim.log.levels.ERROR) end)
  end
end
`)
	for _, mod := range modules {
		fmt.Fprintf(&init, "load('%s')\n", mod)
	}
	init.WriteString("if not vim.g.shoshinvim_probe then\n  local ok, err = pcall(require, 'user_config.user')\n  if not ok then vim.notify(tostring(err), vim.log.levels.WARN) end\nend\n")
	files["init.lua"] = init.String()
	return files, nil
}

// Plugins lists the plugins a state needs, including their requirements. Each choice
// setting names its plugin directly; "native" (or "system") means no plugin.
func Plugins(s State) []string {
	s = withLegacyWorkspace(s)
	set := map[string]bool{}
	for _, pair := range [][2]string{{"navigation.picker", "native"}, {"navigation.explorer", "native"}, {"git.hunks", "native"}, {"formatting.provider", "native"}, {"lsp.provider", "native"}, {"tools.provider", "system"}, {"appearance.statusline", "native"}, {"appearance.buffers", "native"}, {"navigation.shortcuts", "native"}, {"completion.engine", "native"},
		{"workspace.start_screen", "none"}, {"appearance.indent", "none"}, {"appearance.notifications", "none"}, {"editor.detect_indent", "none"}, {"syntax.engine", "native"},
		{"coding.pairs", "none"}, {"coding.surround", "none"}, {"coding.textobjects", "none"}, {"coding.todo", "none"}, {"coding.lint", "none"}, {"coding.debug", "none"}} {
		if v, _ := Value(s, pair[0], pair[1]).(string); v != pair[1] && v != "" {
			set[v] = true
		}
	}
	if p := themePlugin(s); p != "" {
		set[p] = true
	}
	return withRequirements(sorted(set))
}
func pluginLua(s State) string {
	if Value(s, "plugins.manager", "none") != "lazy" {
		return ""
	}
	var b strings.Builder
	b.WriteString(`if vim.g.shoshinvim_probe then return end
local base = vim.fn.stdpath('data') .. '/shoshinvim'
local lazy_path = base .. '/plugins/lazy'
if not vim.uv.fs_stat(lazy_path .. '/lua/lazy/init.lua') then return end
vim.opt.rtp:prepend(lazy_path)
local specs = {}
local function installed(name, spec)
  spec.dir = base .. '/plugins/' .. name
  if vim.uv.fs_stat(spec.dir) then specs[#specs + 1] = spec end
end
`)
	if Value(s, "appearance.buffers", "native") == "barbar" {
		b.WriteString("vim.g.barbar_auto_setup = false -- configured in appearance.lua\n")
	}
	for _, id := range Plugins(s) {
		_, _, dir, err := source(s, id)
		if err != nil {
			continue // Validation reports an incomplete custom theme.
		}
		config := ""
		switch {
		case id == "snacks":
			config = ", priority = 900, opts = " + snacksOptions(s)
		case id == themePlugin(s):
			config = ", priority = 1000"
		case id == "mini.pick", id == "mini.files":
			config = fmt.Sprintf(", main = %s, opts = {}", LuaString(id))
		case id == "guess-indent":
			config = ", main = 'guess-indent', opts = {}"
		case id == "mini.diff":
			config = ", main = 'mini.diff', opts = { view = { style = 'sign', signs = { add = '+', change = '~', delete = '_' } } }"
		case id == "oil", id == "gitsigns":
			config = ", opts = {}"
		case id == "nvim-autopairs", id == "mini.pairs", id == "nvim-surround":
			config = fmt.Sprintf(", main = %s, opts = {}", LuaString(id))
		case id == "mini.surround":
			if Value(s, "keymaps.style", "none") == "lazyvim" {
				// LazyVim's mini-surround extra moves the keys under gs, keeping s for substitute.
				config = ", main = 'mini.surround', opts = { mappings = { add = 'gsa', delete = 'gsd', find = 'gsf', find_left = 'gsF', highlight = 'gsh', replace = 'gsr', update_n_lines = 'gsn' } }"
			} else {
				config = ", main = 'mini.surround', opts = {}"
			}
		case id == "todo-comments":
			config = ", main = 'todo-comments', opts = { signs = false }" // kickstart's setting: no sign column icons.
		case id == "mini.hipatterns":
			config = ", main = 'mini.hipatterns', opts = { highlighters = { " +
				"fixme = { pattern = '%f[%w]()FIXME()%f[%W]', group = 'MiniHipatternsFixme' }, hack = { pattern = '%f[%w]()HACK()%f[%W]', group = 'MiniHipatternsHack' }, " +
				"todo = { pattern = '%f[%w]()TODO()%f[%W]', group = 'MiniHipatternsTodo' }, note = { pattern = '%f[%w]()NOTE()%f[%W]', group = 'MiniHipatternsNote' } } }"
		case id == "mini.ai":
			// kickstart's settings; aa and ii avoid Neovim 0.12's an/in selection keys.
			config = ", main = 'mini.ai', opts = { n_lines = 500, mappings = { around_next = 'aa', inside_next = 'ii' } }"
		case id == "mason":
			config = ", opts = { PATH = 'prepend', install_root_dir = base .. '/mason' }"
		}
		// lazy.nvim expects a plugin inside its root to live at root/<name>.
		fmt.Fprintf(&b, "installed(%s, { name = %s, lazy = false%s })\n", LuaString(dir), LuaString(dir), config)
	}
	// lazy.nvim resets the runtime path to Neovim's own config folder; keep this one too,
	// so `nvim -u <target>/init.lua` still finds the modules loaded after plugins.
	b.WriteString(`local config_root = vim.fn.fnamemodify(debug.getinfo(1, 'S').source:sub(2), ':p:h:h:h')
require('lazy').setup(specs, {
  root = base .. '/plugins', lockfile = base .. '/lazy-lock.json',
  install = { missing = false }, checker = { enabled = false },
  change_detection = { enabled = false }, rocks = { enabled = false },
  pkg = { enabled = false }, local_spec = false,
  performance = { rtp = { paths = { config_root } } },
})
`)
	return b.String()
}

